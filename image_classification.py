def get_model():
  model = keras.Sequential([
    keras.layers.Flatten(input_shape=(32, 32, 3)),
    keras.layers.Dense(3000,activation="relu"), # here we are taking our hidden layers randomly. You can take either 3100 or something
    keras.layers.Dense(1000,activation="relu"),
    keras.layers.Dense(10,activation="sigmoid") # here we are taking 10 output layers because, in our classification we have 10 images to classsify.
  ])
  model.compile(
      optimizer = "SGD",
      loss = "categorical_crossentropy",
      metrics = ["accuracy"]
  )
  return model

with tf.device('CPU:0'):
  cpu_model = get_model()
  cpu_model.fit(X_train_scaled,y_train_categorical,epochs=1)

with tf.device("/GPU:0"):
  gpu_model = get_model()
  gpu_model.fit(X_train_scaled,y_train_categorical,epochs=1)

